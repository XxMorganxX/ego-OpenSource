"""Path lockfile: every path kb-publish may export, approved once.

The manifest selects with coarse globs (`KB_Core/**`, `evals/**`), so on its
own any new nested file — a notes dir, a dumped fixture, a runbook — exports on
the next run and the operator only ever sees "assembled N files". The lockfile
is the memory of what a human has already looked at: a selected path that is
not listed, or a pinned file whose bytes changed, makes kb-publish and
`kb-check-publishable --strict` REFUSE until `kb-publish approve` has shown it
(size + head) and recorded it. The manifest keeps its globs; the lockfile makes
nested new files private until approved.

Pinned (content-hashed) entries are the files whose risk is in the DATA rather
than in a code shape a reviewer skims in a diff:

- `*.jsonl` anywhere, and `*.json` under an `evals/` or fixtures dir — corpus-
  derived rows are the likeliest way real data slips out;
- every exported `*.toml` — live config (routing overrides, sources) drifts
  into these;
- anything that is not strict UTF-8 (media, and the rare text the structural
  scan cannot read). For these the pin IS the review, and the pin is the only
  thing that exempts them from structural.py's UTF-8 refusal.

Everything else is listed by path only: ordinary source edits go through normal
review; what the lockfile adds is that a NEW path is never silent.

The hash is git's blob id (`git hash-object`) of the bytes as exported.

The file lives at private/publish.paths.lock — hard-denied by
manifest.hard_deny_reason, never exported. kb-publish reads it from the ref it
publishes (the committed approval is the one that counts); the guard reads the
checkout it runs in.
"""
from __future__ import annotations

import hashlib
import re
import subprocess
from pathlib import Path
from typing import NamedTuple

from kb_core.publish import manifest, structural

LOCK_REL = "private/publish.paths.lock"

Entries = dict[str, "str | None"]   # path -> pinned blob id, or None (path-only)

_HEADER = """\
# private/publish.paths.lock — every path kb-publish may export.
# Generated by `kb-publish approve`: review the diff, don't hand-edit.
# A selected path missing here, or a pinned file whose content changed, is
# refused by kb-publish and kb-check-publishable --strict until approved.
# Format: <path>[<TAB><git blob id>] — the blob id pins data/config/non-UTF-8 files.
"""

_HEX40 = re.compile(r"[0-9a-f]{40}")
# Directory segments whose *.json is data, not config.
_DATA_DIRS = ("evals",)


class LockError(ValueError):
    """The lockfile can't be trusted to mean what it says — refuse, never guess."""


class LockDiff(NamedTuple):
    new: list[str]        # selected, never approved           -> refuse
    removed: list[str]    # approved, no longer selected        -> report only
    changed: list[str]    # pinned content differs from approval -> refuse

    @property
    def blocking(self) -> bool:
        return bool(self.new or self.changed)


def blob_hash(data: bytes) -> str:
    """git's blob id for `data` — what `git hash-object` prints."""
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def needs_pin(rel: str, data: bytes) -> bool:
    """Whether `rel` is approved by content (hash), not just by path."""
    p = Path(rel)
    suffix = p.suffix.lower()
    dirs = [s.lower() for s in p.parts[:-1]]
    if suffix in (".jsonl", ".toml"):
        return True
    if suffix == ".json" and any(d in _DATA_DIRS or "fixture" in d for d in dirs):
        return True
    return structural.encoding_problem(data) is not None


def snapshot(base: Path, paths: list[str]) -> Entries:
    """The lock entries `paths` (relative to `base`) would be approved as.

    Symlinks and missing files are skipped: export.assemble strips the former
    and the latter (a tracked file deleted in a checkout) has nothing to ship.
    """
    out: Entries = {}
    for rel in paths:
        f = base / rel
        if f.is_symlink() or not f.is_file():
            continue
        data = f.read_bytes()
        out[rel] = blob_hash(data) if needs_pin(rel, data) else None
    return out


def diff(approved: Entries | None, current: Entries) -> LockDiff:
    approved = approved or {}
    new = sorted(p for p in current if p not in approved)
    removed = sorted(p for p in approved if p not in current)
    changed = sorted(
        p for p, h in current.items()
        if p in approved and (h is not None or approved[p] is not None)
        and h != approved[p]
    )
    return LockDiff(new, removed, changed)


def pinned_hook(approved: Entries | None) -> structural.PinnedHook:
    """structural.scan_files' `is_pinned`: exact approved bytes only."""
    approved = approved or {}

    def is_pinned(rel: str, data: bytes) -> bool:
        h = approved.get(rel)
        return h is not None and h == blob_hash(data)

    return is_pinned


# --- file format -------------------------------------------------------------

def _check_path(path: str) -> None:
    # A path the line format can't carry verbatim can never be approved, so it
    # stays "new" — refused — forever. That is the fail-closed outcome.
    if not path:
        raise LockError("empty path")
    if any(c in path for c in "\t\n\r\0"):
        raise LockError(f"path {path!r} contains a tab/newline/NUL")
    if path.startswith("#"):
        raise LockError(f"path {path!r} starts with '#' (reads as a comment)")
    if path != path.strip():
        raise LockError(f"path {path!r} has leading/trailing whitespace")


def render(entries: Entries) -> str:
    lines = []
    for path in sorted(entries):
        _check_path(path)
        h = entries[path]
        if h is not None and not _HEX40.fullmatch(h):
            raise LockError(f"{path}: {h!r} is not a git blob id")
        lines.append(path if h is None else f"{path}\t{h}")
    return _HEADER + "".join(f"{ln}\n" for ln in lines)


def parse(text: str) -> Entries:
    out: Entries = {}
    for n, line in enumerate(text.split("\n"), 1):
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) > 2:
            raise LockError(f"line {n}: more than two tab-separated fields")
        path = fields[0]
        _check_path(path)
        h = fields[1] if len(fields) == 2 else None
        if h is not None and not _HEX40.fullmatch(h):
            raise LockError(f"line {n}: {h!r} is not a git blob id")
        if path in out:
            raise LockError(f"line {n}: duplicate path {path!r}")
        out[path] = h
    return out


def parse_bytes(data: bytes) -> Entries:
    try:
        return parse(data.decode("utf-8", errors="strict"))
    except UnicodeDecodeError as e:
        raise LockError(f"not valid UTF-8: {e}") from e


def load(root: Path) -> Entries | None:
    """The working-tree lockfile, or None if there is none."""
    p = root / LOCK_REL
    return parse_bytes(p.read_bytes()) if p.is_file() else None


def load_at_ref(root: Path, ref: str) -> Entries | None:
    """The lockfile committed at `ref`, or None if that ref has none."""
    out = subprocess.run(["git", "ls-tree", "-z", ref, "--", LOCK_REL], cwd=root,
                         check=True, capture_output=True).stdout.decode()
    entry = out.rstrip("\0")
    if not entry:
        return None
    mode, kind, oid = entry.split("\t", 1)[0].split()
    if kind != "blob" or mode not in ("100644", "100755"):
        raise LockError(f"{LOCK_REL} at {ref} is a {kind} (mode {mode}), not a regular file")
    data = subprocess.run(["git", "cat-file", "blob", oid], cwd=root,
                          check=True, capture_output=True).stdout
    return parse_bytes(data)


# --- review output -----------------------------------------------------------

def report_lines(d: LockDiff, total: int, *, have_lock: bool = True) -> list[str]:
    """The path diff, printed by kb-publish (every run) and the guard.

    Every new and changed path is listed — that list IS the review prompt. With
    no lockfile at all every path is new; only the count is useful then.
    """
    if not have_lock:
        return [f"no {LOCK_REL} — all {total} selected path(s) are unapproved"]
    out = [f"lockfile: {len(d.new)} new, {len(d.changed)} changed, "
           f"{len(d.removed)} removed (of {total} selected)"]
    out += [f"  + {p}" for p in d.new]
    out += [f"  ~ {p}  (pinned content changed)" for p in d.changed]
    out += [f"  - {p}  (no longer exported — reported, not refused)" for p in d.removed]
    return out


_HEAD_LINES = 5
_HEAD_WIDTH = 160


def _printable(line: str) -> str:
    # The head goes straight to a terminal: neutralize escapes so a file can't
    # repaint the screen (or hide its own lines) while being reviewed.
    return "".join(c if c.isprintable() or c == "\t" else repr(c)[1:-1] for c in line)


_STRINGS = re.compile(r"[\x20-\x7e]{6,}")


def _strings(data: bytes, limit: int = _HEAD_LINES) -> list[str]:
    """Printable runs, like strings(1), from the raw bytes and UTF-16 readings."""
    out: list[str] = []
    readings = [data.decode("latin-1"), *structural.utf16_readings(data)]
    for text in readings:
        for run in _STRINGS.findall(text):
            if run not in out:
                out.append(run)
            if len(out) >= limit:
                return out
    return out


def describe(rel: str, data: bytes) -> str:
    """`rel` for human review: size and the first lines, or for binary content its
    detected type and printable strings (never a blind "not shown")."""
    head = f"{rel}  ({len(data)} bytes)"
    kind = structural.container_magic(data)
    problem = structural.encoding_problem(data)
    if kind or problem or Path(rel).suffix.lower() in manifest.MEDIA_SUFFIXES:
        what = (f"{kind} container — never approvable" if kind
                else problem or "media")
        body = "".join(f"\n    strings| {_printable(s)[:_HEAD_WIDTH]}" for s in _strings(data))
        return (f"{head}\n    binary — {what}; approval pins its hash"
                + (body or "\n    (no printable strings)"))
    lines = data.decode("utf-8").splitlines()[:_HEAD_LINES]
    body = "".join(f"\n    | {_printable(ln)[:_HEAD_WIDTH]}" for ln in lines)
    return head + (body or "\n    (empty)")
