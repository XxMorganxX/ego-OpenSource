"""Tenant registry: who exists, which database they own, how their agent authenticates.

One TOML file (KB_TENANTS_CONFIG, default <KB_Core>/tenants.toml; gitignored + git-excluded;
mode 0600 — it holds HMAC secrets and database passwords). A missing file is an owner-only
registry, so every service keeps today's single-tenant behaviour with zero configuration.

Every tenant has its own Postgres login: role `kb_t_<slug>` owns database `kb_t_<slug>`,
nobody else may connect to it, and `db_password` here is that role's password. The
owner's app role (KB_APP_USER) never reaches a tenant database, and a tenant role never
reaches the owner's or another tenant's: a DSN that pairs one tenant's credential with
another database fails to connect instead of serving the wrong data.
"""
from __future__ import annotations

import os
import re
import sys
import threading
import time
import tomllib
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import quote, urlsplit, urlunsplit

OWNER_SLUG = "owner"
SLUG_RE = re.compile(r"^[a-z][a-z0-9_]{1,30}$")
MIN_SECRET_LEN = 32
_RELOAD_CHECK_S = 10.0
_OWNER_KEYS = {"emails", "database", "policy", "prompts_overlay", "library_tokens"}
_TENANT_KEYS = {"emails", "database", "agent_secret", "db_password", "vault_layer", "policy",
                "prompts_overlay", "enabled", "library_tokens"}
# Generated by `kb-tenant create` (secrets.token_hex); the charset keeps it safe inside a
# DSN's userinfo and a SQL literal without quoting games.
DB_PASSWORD_RE = re.compile(r"^[A-Za-z0-9]{32,128}$")


class RegistryError(RuntimeError):
    """tenants.toml is malformed or inconsistent. Loud at load, never a silent default."""


@dataclass(frozen=True)
class Tenant:
    slug: str
    emails: frozenset[str]
    database: str
    agent_secret: str | None = None
    # The tenant's own Postgres login (role kb_t_<slug>, set by parse_registry). None only
    # for the owner, who connects as KB_DATABASE_URL's role; dsn_for refuses a tenant
    # without one rather than fall back to the owner's credentials.
    db_role: str | None = None
    db_password: str | None = None
    vault_layer: str = "Obsidian"
    policy_path: Path | None = None
    prompts_overlay: Path | None = None
    enabled: bool = True
    library_tokens: frozenset[str] = frozenset()

    @property
    def is_owner(self) -> bool:
        return self.slug == OWNER_SLUG


def _emails(raw, where: str) -> frozenset[str]:
    if (not isinstance(raw, list) or not raw
            or not all(isinstance(e, str) and "@" in e for e in raw)):
        raise RegistryError(f"{where}: emails must be a non-empty list of addresses")
    return frozenset(e.strip().lower() for e in raw)


def _library_tokens(raw, where: str) -> frozenset[str]:
    """Cloudflare Access service-token Client IDs (one per device) whose download-only
    requests (GET /api/library/*) are served as this tenant."""
    if raw is None:
        return frozenset()
    if not isinstance(raw, list) or not all(isinstance(t, str) and t.strip() for t in raw):
        raise RegistryError(f"{where}: library_tokens must be a list of service-token Client IDs")
    return frozenset(t.strip() for t in raw)


def _path(raw, base: Path, where: str, key: str) -> Path | None:
    if raw is None:
        return None
    if not isinstance(raw, str):
        raise RegistryError(f"{where}: {key} must be a string path")
    p = Path(raw)
    return p if p.is_absolute() else (base / p).resolve()


def parse_registry(data: dict, *, base: Path, env) -> tuple[Tenant, dict[str, Tenant]]:
    """Pure: TOML dict -> (owner, tenants). Raises RegistryError on any inconsistency."""
    unknown_top = set(data) - {"owner", "tenant"}
    if unknown_top:
        raise RegistryError(f"unknown top-level key(s) {sorted(unknown_top)} "
                            "(allowed: owner, tenant)")
    owner_block = data.get("owner", {})
    if not isinstance(owner_block, dict):
        raise RegistryError("[owner]: must be a table")
    tenant_blocks = data.get("tenant", {})
    if not isinstance(tenant_blocks, dict):
        raise RegistryError("tenant: must be a table of [tenant.<slug>] tables")
    bad = set(owner_block) - _OWNER_KEYS
    if bad:
        raise RegistryError(f"[owner]: unknown key(s) {sorted(bad)}")
    if "emails" in owner_block:
        owner_emails = _emails(owner_block["emails"], "[owner]")
    else:
        owner_emails = [e for e in env.get("KB_CF_ACCESS_EMAILS", "").split(",") if e.strip()]
    owner = Tenant(
        slug=OWNER_SLUG,
        emails=frozenset(e.strip().lower() for e in owner_emails),
        database=str(owner_block.get("database") or env.get("POSTGRES_DB") or "kb_mcp"),
        policy_path=_path(owner_block.get("policy"), base, "[owner]", "policy"),
        prompts_overlay=_path(owner_block.get("prompts_overlay"), base, "[owner]",
                              "prompts_overlay"),
        library_tokens=_library_tokens(owner_block.get("library_tokens"), "[owner]"),
    )
    tenants: dict[str, Tenant] = {}
    seen: dict[str, str] = {e: OWNER_SLUG for e in owner.emails}
    # A device token resolves to exactly one tenant. Disabled tenants count, as for secrets.
    token_owner: dict[str, str] = {t: "[owner]" for t in owner.library_tokens}
    # The gateway looks the secret up by the claimed X-KB-Tenant, so two tenants sharing one
    # could each sign as the other. Disabled tenants count: re-enabling must not collide.
    secret_owner: dict[str, str] = {}
    for slug, block in tenant_blocks.items():
        where = f"[tenant.{slug}]"
        if not SLUG_RE.match(slug) or slug == OWNER_SLUG:
            raise RegistryError(f"{where}: slug must match {SLUG_RE.pattern} and not be 'owner'")
        if not isinstance(block, dict):
            raise RegistryError(f"{where}: must be a table")
        bad = set(block) - _TENANT_KEYS
        if bad:
            raise RegistryError(f"{where}: unknown key(s) {sorted(bad)}")
        database = str(block.get("database") or f"kb_t_{slug}")
        if database != f"kb_t_{slug}":
            raise RegistryError(f"{where}: database must be 'kb_t_{slug}' (got {database!r})")
        secret = block.get("agent_secret")
        if not isinstance(secret, str) or len(secret) < MIN_SECRET_LEN:
            raise RegistryError(f"{where}: agent_secret must be a string of at least "
                                f"{MIN_SECRET_LEN} characters")
        if secret in secret_owner:
            raise RegistryError(f"{where}: agent_secret is already used by "
                                f"[tenant.{secret_owner[secret]}]; every tenant needs its own "
                                "(kb-tenant rotate-secret)")
        secret_owner[secret] = slug
        db_password = block.get("db_password")
        if not isinstance(db_password, str) or not DB_PASSWORD_RE.match(db_password):
            raise RegistryError(
                f"{where}: db_password must be 32-128 letters/digits (the password of role "
                f"kb_t_{slug}). An entry without one predates per-tenant database roles: "
                "back it up, `kb-tenant delete` it, `kb-tenant create` it again and restore "
                "the backup into it (docs/ops/backup-restore.md)")
        emails = _emails(block.get("emails"), where)
        for e in emails:
            if e in seen:
                raise RegistryError(f"{where}: email {e} already belongs to {seen[e]}")
            seen[e] = slug
        vault_layer = block.get("vault_layer", "Obsidian")
        if not isinstance(vault_layer, str):
            raise RegistryError(f"{where}: vault_layer must be a string")
        enabled = block.get("enabled", True)
        if not isinstance(enabled, bool):
            raise RegistryError(f"{where}: enabled must be true or false (got {enabled!r})")
        library_tokens = _library_tokens(block.get("library_tokens"), where)
        for t in sorted(library_tokens):
            if t in token_owner:
                raise RegistryError(f"{where}: library token {t!r} is already used by "
                                    f"{token_owner[t]}; every device token maps to one tenant")
            token_owner[t] = where
        tenants[slug] = Tenant(
            slug=slug, emails=emails, database=database, agent_secret=secret,
            db_role=database, db_password=db_password, vault_layer=vault_layer,
            policy_path=_path(block.get("policy"), base, where, "policy"),
            prompts_overlay=_path(block.get("prompts_overlay"), base, where, "prompts_overlay"),
            enabled=enabled, library_tokens=library_tokens,
        )
    return owner, tenants


class Registry:
    """The parsed registry. Re-reads its file when the mtime changes (checked at most once
    per _RELOAD_CHECK_S); a reload that fails validation keeps the previous registry."""

    def __init__(self, owner: Tenant, tenants: dict[str, Tenant], *,
                 path: Path | None = None, env=None) -> None:
        self._owner = owner
        self._tenants = dict(tenants)
        self._path = path
        self._env = os.environ if env is None else env
        self._mtime = path.stat().st_mtime if path is not None and path.exists() else None
        self._checked_at = time.monotonic()
        self._lock = threading.Lock()

    @property
    def owner(self) -> Tenant:
        self._maybe_reload()
        return self._owner

    @property
    def path(self) -> Path | None:
        return self._path

    def tenants(self, *, include_owner: bool = True,
                include_disabled: bool = False) -> list[Tenant]:
        self._maybe_reload()
        out = [self._owner] if include_owner else []
        out += [t for t in self._tenants.values() if include_disabled or t.enabled]
        return out

    def by_slug(self, slug: str) -> Tenant | None:
        self._maybe_reload()
        if slug == OWNER_SLUG:
            return self._owner
        return self._tenants.get(slug)

    def by_email(self, email: str) -> Tenant | None:
        self._maybe_reload()
        e = (email or "").strip().lower()
        if e in self._owner.emails:
            return self._owner
        for t in self._tenants.values():
            if t.enabled and e in t.emails:
                return t
        return None

    def by_library_token(self, client_id: str) -> Tenant | None:
        """The tenant whose `library_tokens` lists this service-token Client ID (a device's
        download-only credential), or None. Disabled tenants never resolve."""
        self._maybe_reload()
        c = (client_id or "").strip()
        if not c:
            return None
        if c in self._owner.library_tokens:
            return self._owner
        for t in self._tenants.values():
            if t.enabled and c in t.library_tokens:
                return t
        return None

    def all_emails(self) -> frozenset[str]:
        return frozenset(e for t in self.tenants() for e in t.emails)

    def dsn_for(self, tenant: Tenant, env=None) -> str:
        """The DSN this tenant's database answers on. Host, port and query always follow
        the environment (KB_DATABASE_URL when set: every service, every test). The owner
        connects with the environment's credentials; a tenant ONLY with its own role and
        password, never the owner's (RegistryError if it has none)."""
        env = self._env if env is None else env
        base = env.get("KB_DATABASE_URL")
        if base and tenant.is_owner:
            return base
        if not tenant.is_owner and not (tenant.db_role and tenant.db_password):
            raise RegistryError(f"tenant {tenant.slug} has no database role/password; "
                                "refusing to connect it with the owner's credentials")
        if base:
            parts = urlsplit(base)
            netloc = parts.netloc.rpartition("@")[2]
            netloc = f"{quote(tenant.db_role, safe='')}:{quote(tenant.db_password, safe='')}@{netloc}"
            return urlunsplit((parts.scheme, netloc, f"/{tenant.database}",
                               parts.query, parts.fragment))
        port = env.get("DB_HOST_PORT", "5433")
        if tenant.is_owner:
            user = env.get("KB_APP_USER") or env.get("POSTGRES_USER") or ""
            pw = env.get("KB_APP_PASSWORD") or env.get("POSTGRES_PASSWORD") or ""
            return f"postgresql://{user}:{pw}@localhost:{port}/{tenant.database}"
        return (f"postgresql://{quote(tenant.db_role, safe='')}:"
                f"{quote(tenant.db_password, safe='')}@localhost:{port}/{tenant.database}")

    def _maybe_reload(self) -> None:
        if self._path is None:
            return
        now = time.monotonic()
        if now - self._checked_at < _RELOAD_CHECK_S:
            return
        with self._lock:
            self._checked_at = now
            try:
                mtime = self._path.stat().st_mtime
            except FileNotFoundError:
                return                                  # keep the last good registry
            if mtime == self._mtime:
                return
            try:
                fresh = load_registry(self._path, env=self._env)
            except RegistryError as exc:
                print(f"WARNING: {self._path} reload failed, keeping previous registry: {exc}",
                      file=sys.stderr, flush=True)
                self._mtime = mtime
                return
            self._owner, self._tenants, self._mtime = fresh._owner, fresh._tenants, mtime


def core_root() -> Path | None:
    """The KB_Core project root (the directory holding pyproject.toml and .env) of this
    editable kb_core install, or None when kb_core is not running from a checkout."""
    root = Path(__file__).resolve().parents[2]
    return root if (root / "pyproject.toml").is_file() else None


def registry_path(env=None) -> Path:
    """KB_TENANTS_CONFIG, else tenants.toml in the KB_Core root — never the process cwd:
    KB_MCP runs from ../KB_MCP and must read the same file as the dashboard and gateway.
    Falls back to ./tenants.toml only outside a checkout."""
    env = os.environ if env is None else env
    explicit = env.get("KB_TENANTS_CONFIG")
    if explicit:
        return Path(explicit)
    root = core_root()
    return root / "tenants.toml" if root is not None else Path("tenants.toml")


TENANT_POLICY_FILE = "policy.tenant.toml"


def tenant_neutral_policy_path() -> Path:
    """The shipped tenant-neutral policy (shipped defaults, no prompt overlay) that a
    tenant with no registry policy runs on. Absolute; RegistryError when absent, so a
    tenant daemon can never start without one."""
    root = core_root()
    path = (root if root is not None else Path.cwd().resolve()) / TENANT_POLICY_FILE
    if not path.is_file():
        raise RegistryError(f"{path} is missing: tenant daemons need the shipped "
                            "tenant-neutral policy")
    return path


def load_registry(path: Path | str | None = None, env=None) -> Registry:
    env = os.environ if env is None else env
    p = Path(path) if path is not None else registry_path(env)
    if not p.exists():
        owner, tenants = parse_registry({}, base=p.parent, env=env)
        return Registry(owner, tenants, path=p, env=env)
    try:
        data = tomllib.loads(p.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        raise RegistryError(f"{p}: {exc}") from None
    owner, tenants = parse_registry(data, base=p.parent.resolve(), env=env)
    return Registry(owner, tenants, path=p, env=env)


def main(argv: list[str] | None = None) -> int:
    """`python -m kb_core.tenants dsn <slug>` prints the DSN; `env <slug>` prints the
    KEY=VALUE lines kb-svc.sh exports in tenant mode."""
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2 or argv[0] not in ("dsn", "env"):
        print("usage: python -m kb_core.tenants dsn|env <slug>", file=sys.stderr)
        return 64
    reg = load_registry()
    t = reg.by_slug(argv[1])
    if t is None:
        print(f"unknown tenant {argv[1]!r}", file=sys.stderr)
        return 2
    if argv[0] == "dsn":
        print(reg.dsn_for(t))
        return 0
    lines = [f"KB_DATABASE_URL={reg.dsn_for(t)}", f"KB_VAULT_LAYER={t.vault_layer}"]
    if t.policy_path is not None:
        lines.append(f"KB_POLICY_CONFIG={t.policy_path}")
    elif not t.is_owner:
        # Never leave a tenant on load_policy()'s ./policy.toml fallback (the owner's).
        try:
            lines.append(f"KB_POLICY_CONFIG={tenant_neutral_policy_path()}")
        except RegistryError as exc:
            print(str(exc), file=sys.stderr)
            return 2
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
